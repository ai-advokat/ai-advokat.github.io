import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const workerRoot = new URL("../src/", import.meta.url);
const generatedName = "case-response-worker-policy.js";

function bundledPolicyFiles(folder, prefix = "") {
  return readdirSync(folder, {withFileTypes:true}).flatMap(entry => {
    const path = prefix + entry.name;
    if (entry.isDirectory()) return bundledPolicyFiles(new URL(entry.name + "/", folder), path + "/");
    return entry.isFile() && path !== generatedName && /\.(js|mjs|json)$/.test(path) ? [path] : [];
  });
}

export function caseResponseWorkerPolicyDigest() {
  const hash = createHash("sha256");
  for (const path of bundledPolicyFiles(workerRoot).sort()) {
    const source = readFileSync(new URL(path, workerRoot), "utf8").replace(/\r\n/g, "\n");
    hash.update(JSON.stringify([path, source]));
  }
  return hash.digest("hex");
}

function generatedPolicyModule(digest) {
  return "// Generated by node scripts/case-response-worker-policy.mjs --write\n"
    + `export const CASE_RESPONSE_WORKER_POLICY_SHA256 = "${digest}";\n`;
}

export function verifyCaseResponseWorkerPolicy() {
  const generated = readFileSync(new URL(generatedName, workerRoot), "utf8").replace(/\r\n/g, "\n");
  return generated === generatedPolicyModule(caseResponseWorkerPolicyDigest());
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const digest = caseResponseWorkerPolicyDigest();
  if (process.argv[2] === "--write") {
    writeFileSync(new URL(generatedName, workerRoot), generatedPolicyModule(digest));
  }
  process.stdout.write(digest + "\n");
}
