export const CASE_LAW_METADATA_VERSION = "1.1.0";
export const CASE_LAW_METADATA_SCHEMA = "AI_ADVOCAT_CASE_LAW_METADATA_V1";

const CONTROL=/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F\u202A-\u202E\u2066-\u2069]/u;
const MAX_TEXT=2_000_000;
const MAX_BATCH=500;
const SOURCE_CLASSES=new Set(["local_unverified","official_public","licensed_secondary_export"]);

function clean(value,max=MAX_TEXT){
  if(typeof value!=="string") throw new TypeError("case_law_text_required");
  const s=value.normalize("NFKC").replace(/\r\n?/g,"\n").trim();
  if(!s) throw new TypeError("case_law_text_required");
  if(s.length>max) throw new TypeError("case_law_text_too_large");
  if(CONTROL.test(s)) throw new TypeError("case_law_control_character");
  return s;
}
function unique(values,limit=100){
  return [...new Set(values.map(v=>String(v??"").trim()).filter(Boolean))].slice(0,limit);
}
function matchAll(text,re,group=1,limit=100){
  const flags=re.flags.includes("g")?re.flags:re.flags+"g";
  const rx=new RegExp(re.source,flags);
  const out=[];
  for(const m of text.matchAll(rx)){
    const v=String(m[group]??m[0]??"").trim();
    if(v) out.push(v);
    if(out.length>=limit) break;
  }
  return unique(out,limit);
}
function firstMatch(text,patterns){
  for(const re of patterns){
    const m=text.match(re);
    if(m) return String(m[1]??m[0]).replace(/\s+/g," ").trim();
  }
  return null;
}
function snippet(text,re,max=1600){
  const m=text.match(re);
  if(!m) return null;
  return String(m[1]??m[0]).replace(/\s+/g," ").trim().slice(0,max)||null;
}
function normalizeSourceClass(value){
  const v=String(value||"local_unverified").trim();
  if(!SOURCE_CLASSES.has(v)) throw new TypeError("case_law_source_class_invalid");
  return v;
}
function normalizeSourceUrl(value){
  if(value===null||value===undefined||value==="") return null;
  const text=String(value).trim();
  let url;
  try{url=new URL(text);}catch{throw new TypeError("case_law_source_url_invalid");}
  return url.href;
}
function normalizeSha256(value){
  if(value===null||value===undefined||value==="") return null;
  const v=String(value).trim().toLowerCase();
  if(!/^[a-f0-9]{64}$/.test(v)) throw new TypeError("case_law_source_sha256_invalid");
  return v;
}

export function normalizeDecisionDateCandidate(value){
  const raw=String(value??"").trim();
  const m=raw.match(/^(\d{1,2})[.\/-](\d{1,2})[.\/-](\d{4})$/);
  if(!m) return null;
  const day=Number(m[1]),month=Number(m[2]),year=Number(m[3]);
  const d=new Date(Date.UTC(year,month-1,day));
  if(d.getUTCFullYear()!==year||d.getUTCMonth()!==month-1||d.getUTCDate()!==day) return null;
  return `${String(year).padStart(4,"0")}-${String(month).padStart(2,"0")}-${String(day).padStart(2,"0")}`;
}

export function extractLiteralEcli(textInput){
  const text=clean(textInput);
  const found=matchAll(text,/\b(ECLI:[A-Z]{2}:[A-Z0-9]+:[0-9]{4}:[A-Z0-9.]+)\b/giu,1,20);
  return Object.freeze({
    values:found,
    primary:found[0]||null,
    generated:null,
    rule:"ECLI is preserved only when literally present in the source; domestic ECLI is never generated by AI Advokat."
  });
}

export function extractDomesticCaseNumbers(textInput){
  const text=clean(textInput);
  return matchAll(
    text,
    /(?<![\p{L}\p{N}])((?:У\.?бр\.?|К\.?бр\.?|КПП?\.?бр\.?|П\.?бр\.?|ПЛ\.?бр\.?|Т\.?бр\.?|ТКР\.?бр\.?|Рев\.?бр\.?|УСПИ?\.?бр\.?|УЖ\.?бр\.?|УЖР\.?бр\.?)\s*[\p{L}\p{N}./-]{1,48})(?![\p{L}\p{N}])/giu,
    1,
    30
  );
}

export function extractCourt(textInput){
  const text=clean(textInput);
  return firstMatch(text,[
    /((?:Врховен|Уставен|Управен|Виш\s+управен|Апелационен|Основен(?:\s+кривичен)?)\s+суд(?:\s+на\s+Република\s+Северна\s+Македонија|\s+во\s+[А-ЯЀ-ӿ][^\n,.;]{0,70}|\s+[А-ЯЀ-ӿ][^\n,.;]{0,70})?)/iu,
    /СУД\s*[:\-–—]?\s*([^\n,;]{3,120})/iu
  ]);
}

export function extractDecisionDateCandidates(textInput){
  const text=clean(textInput);
  const aroundDecision=matchAll(text,/(?:донес(?:е|ена|ено)|одржана\s+на|датум(?:от)?\s+на\s+одлук(?:а|ата)|од)\s*[:\-]?\s*(\d{1,2}[.\/-]\d{1,2}[.\/-]\d{4})/giu,1,20);
  const any=matchAll(text,/\b(\d{1,2}[.\/-]\d{1,2}[.\/-]\d{4})\b/gu,1,50);
  return unique([...aroundDecision,...any],50);
}

export function extractDecisionType(textInput){
  const text=clean(textInput);
  return firstMatch(text,[
    /(?<![\p{L}\p{N}])(ПРЕСУДА|РЕШЕНИЕ|ОДЛУКА|ЗАКЛУЧОК|НАРЕДБА|ОПРЕДЕЛЕНИЕ)(?![\p{L}\p{N}])/u,
    /(?<![\p{L}\p{N}])(пресуда|решение|одлука|заклучок|наредба|определение)(?![\p{L}\p{N}])/iu
  ]);
}

export function classifyRecordKind(decisionType){
  const value=String(decisionType||"").toLocaleLowerCase("mk");
  if(value==="пресуда") return "judgment";
  if(value==="решение") return "ruling";
  if(value==="одлука") return "decision";
  if(value==="заклучок") return "conclusion";
  if(value==="наредба") return "order";
  if(value==="определение") return "order";
  return "unknown";
}

export function extractLegalArea(textInput){
  const text=clean(textInput).toLocaleLowerCase("mk");
  const scored=[
    ["кривично",["обвинет","обвинение","кривично дело","јавен обвинител","казна"]],
    ["граѓанско",["тужител","тужен","тужбено барање","парнична постапка"]],
    ["управно",["управен спор","управен суд","тужба против решение","управен акт"]],
    ["работно",["работен однос","работник","работодавач","отказ"]],
    ["трговско",["трговски спор","трговско друштво","стечај","договор за купопродажба"]],
    ["прекршочно",["прекршок","прекршочна постапка"]]
  ].map(([area,terms])=>({area,score:terms.reduce((n,t)=>n+(text.includes(t)?1:0),0),matched:terms.filter(t=>text.includes(t))}))
   .sort((a,b)=>b.score-a.score);
  const top=scored[0];
  return Object.freeze({value:top.score?top.area:null,matched:top.score?top.matched:[],method:"deterministic_terms",statisticalConfidence:null});
}

export function extractLegalCitations(textInput){
  const text=clean(textInput);
  const articles=matchAll(text,/(?:член|чл\.)\s*(\d+[а-шa-z]?(?:\s*(?:став|ст\.)\s*\(?\d+\)?)?(?:\s*(?:точка|т\.)\s*\d+)?)/giu,1,80);
  const laws=matchAll(text,/(?<![\p{L}\p{N}])((?:Закон(?:от)?\s+за\s+[^\n.;:]{2,160}|Кривич(?:ен|ниот)\s+законик|Устав(?:от)?(?:\s+на\s+Република\s+Северна\s+Македонија)?))/giu,1,50).map(x=>x.replace(/\s+/g," "));
  return Object.freeze({articles:unique(articles,80),laws:unique(laws,50)});
}

export function extractEchrCompatibility(textInput){
  const text=clean(textInput);
  const echrEcli=matchAll(text,/\b(ECLI:CE:ECHR:[0-9]{4}:[A-Z0-9.]+)\b/giu,1,20);
  const conventionArticles=unique([
    ...matchAll(text,/(?:член|чл\.?)\s*(\d+(?:\s*(?:став|§)\s*\d+)?)\s+од\s+(?:Европската\s+конвенција|ЕКЧП)/giu,1,30),
    ...matchAll(text,/(?:Article|Art\.?)\s*(\d+(?:\s*§\s*\d+)?)\s+(?:ECHR|of\s+the\s+Convention)/giu,1,30)
  ],30);
  const applicationNumbers=matchAll(text,/(?:апликаци(?:ја|јата)|application(?:\s+no\.)?|ЕСЧП|ECHR)[^\n]{0,80}?\b(\d{1,6}\/\d{2})\b/giu,1,20);
  const hudocItemIds=matchAll(text,/hudoc\.echr\.coe\.int\/(?:eng|fre)\?i=(\d{3}-\d+)/giu,1,20);
  return Object.freeze({
    ecli:echrEcli,
    applicationNumbers,
    hudocItemIds,
    conventionArticles,
    hudocCompatibleFields:["case_title","application_number","respondent_state","document_type","date","importance","conclusion","articles","keywords","domestic_law","strasbourg_case_law","ecli"]
  });
}

export function extractDisposition(textInput){
  const text=clean(textInput);
  return snippet(text,/(?:ПРЕСУДИ|ОДЛУЧИ|РЕШИ|ДИСПОЗИТИВ)\s*[:\-–—]?\s*([\s\S]{1,2400}?)(?=\n\s*(?:ОБРАЗЛОЖЕНИЕ|О\s*б\s*р\s*а\s*з\s*л\s*о\s*ж\s*е\s*н\s*и\s*е|Причини|$))/iu,1800)
    || firstMatch(text,[/(СЕ\s+(?:УВАЖУВА|ОДБИВА|ОТФРЛА|ПОНИШТУВА|ПОТВРДУВА|ПРЕИНАЧУВА)[^\n]{0,600})/iu]);
}

export function extractFinality(textInput){
  const text=clean(textInput).toLocaleLowerCase("mk");
  if(/неправосилн(?:а|о|и)/u.test(text)) return "source_mentions_nonfinal";
  if(/правосилн(?:а|о|и|оста)/u.test(text)) return "source_mentions_finality";
  return "unknown";
}

export function detectPrivacyReviewFlags(textInput){
  const text=clean(textInput);
  const flags=[];
  if(/(?<!\d)\d{13}(?!\d)/u.test(text)) flags.push("possible_personal_id_13_digits");
  if(/\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/iu.test(text)) flags.push("email_present");
  if(/(?:\+389|0)\s*\d{1,2}[\s\/-]*\d{3}[\s\/-]*\d{3,4}/u.test(text)) flags.push("phone_present");
  if(/(?:сведок|оштетен(?:иот|ата)?|малолетн(?:ик|о|а)|жртва)/iu.test(text)) flags.push("special_anonymisation_review_required");
  if(/(?:адреса|живеалиште|престојувалиште|седиште)\s*[:\-]/iu.test(text)) flags.push("address_field_present");
  return Object.freeze(unique(flags,20));
}

export function deterministicMetadataCompleteness(record){
  const checks=[
    ["court",Boolean(record.court)],
    ["case_number",Boolean(record.caseNumber)],
    ["decision_date_candidate",Boolean(record.decisionDate)],
    ["decision_type",Boolean(record.decisionType)],
    ["legal_area",Boolean(record.legalArea?.value)],
    ["legal_citation",Boolean(record.citations.articles.length||record.citations.laws.length)]
  ];
  const passed=checks.filter(([,ok])=>ok).length;
  return Object.freeze({
    label:"deterministic_metadata_completeness",
    passed,
    total:checks.length,
    score:Math.round((passed/checks.length)*100),
    statisticalConfidence:null,
    checks:Object.freeze(checks.map(([id,ok])=>Object.freeze({id,passed:Boolean(ok)})))
  });
}

function sourceBindingState({sourceClass,sourceUrl,sourceSha256}){
  const reasons=[];
  if(sourceClass==="local_unverified") reasons.push("source_class_unverified");
  if(!sourceUrl) reasons.push("official_source_url_missing");
  if(!sourceSha256) reasons.push("source_sha256_missing");
  if(sourceUrl && !sourceUrl.startsWith("https://")) reasons.push("source_url_not_https");
  const stagingCandidate=sourceClass!=="local_unverified" && Boolean(sourceUrl) && Boolean(sourceSha256) && sourceUrl.startsWith("https://");
  return Object.freeze({
    status:stagingCandidate?"claimed_source_bound_pending_verification":"discovery_only_unbound",
    officialBindingVerified:false,
    stagingCandidate,
    reasons:Object.freeze(reasons)
  });
}

export function extractCaseLawMetadata(textInput,{
  filename="judgment.txt",
  sourceUrl=null,
  sourceClass="local_unverified",
  sourceSha256=null,
  sourceHashBasis=null
}={}){
  const text=clean(textInput);
  const normalizedSourceClass=normalizeSourceClass(sourceClass);
  const normalizedSourceUrl=normalizeSourceUrl(sourceUrl);
  const normalizedSourceSha256=normalizeSha256(sourceSha256);
  const caseNumbers=extractDomesticCaseNumbers(text);
  const literalEcli=extractLiteralEcli(text);
  const court=extractCourt(text);
  const dates=extractDecisionDateCandidates(text);
  const decisionType=extractDecisionType(text);
  const legalArea=extractLegalArea(text);
  const citations=extractLegalCitations(text);
  const echr=extractEchrCompatibility(text);
  const privacyFlags=detectPrivacyReviewFlags(text);
  const decisionDate=dates[0]||null;
  const decisionDateIso=dates.map(normalizeDecisionDateCandidate).find(Boolean)||null;
  const binding=sourceBindingState({
    sourceClass:normalizedSourceClass,
    sourceUrl:normalizedSourceUrl,
    sourceSha256:normalizedSourceSha256
  });
  const record={
    schemaVersion:CASE_LAW_METADATA_SCHEMA,
    processorVersion:CASE_LAW_METADATA_VERSION,
    kind:"case_law",
    recordKind:classifyRecordKind(decisionType),
    sourceIdentity:{
      filename:String(filename).slice(0,240),
      sourceUrl:normalizedSourceUrl,
      sourceClass:normalizedSourceClass,
      sourceSha256:normalizedSourceSha256,
      sourceHashBasis:sourceHashBasis?String(sourceHashBasis).slice(0,120):null
    },
    sourceBinding:binding,
    authorityClass:"unverified_or_secondary",
    locator:normalizedSourceUrl||String(filename).slice(0,240),
    releaseRole:"working_metadata",
    humanReviewStatus:"pending",
    authorityReviewStatus:"pending",
    legalAuthority:"not_verified",
    jurisdiction:"MK",
    court,
    caseNumber:caseNumbers[0]||null,
    caseNumberCandidates:caseNumbers,
    relatedCaseNumbers:caseNumbers.slice(1),
    decisionDate,
    decisionDateIso,
    decisionDateCandidates:dates,
    decisionType,
    legalArea,
    finalityStatus:extractFinality(text),
    ecli:literalEcli,
    citations,
    disposition:extractDisposition(text),
    echr,
    privacyReview:{required:privacyFlags.length>0,flags:privacyFlags,automaticRedactionPerformed:false},
    publicationReview:{required:true,status:"pending",note:"Public release requires current Macedonian publication/anonymisation review and Human Gate."},
    generatedOfficialIdentifier:false
  };
  record.completeness=deterministicMetadataCompleteness(record);
  return Object.freeze(record);
}

export function buildCaseLawMetadataBatch(documents=[]){
  if(!Array.isArray(documents)) throw new TypeError("case_law_documents_array_required");
  if(documents.length>MAX_BATCH) throw new TypeError("case_law_batch_limit_exceeded");
  const raw=documents.map((d,i)=>extractCaseLawMetadata(d?.text,{
    filename:d?.filename||`judgment-${i+1}.txt`,
    sourceUrl:d?.sourceUrl||null,
    sourceClass:d?.sourceClass||"local_unverified",
    sourceSha256:d?.sourceSha256||null,
    sourceHashBasis:d?.sourceHashBasis||null
  }));
  const seenHashes=new Map();
  let duplicateHashCount=0;
  const records=raw.map((r,i)=>{
    const hash=r.sourceIdentity.sourceSha256;
    let duplicateOfIndex=null;
    let status="not_evaluated";
    if(hash){
      if(seenHashes.has(hash)){
        duplicateOfIndex=seenHashes.get(hash);
        status="duplicate_content_hash";
        duplicateHashCount++;
      }else{
        seenHashes.set(hash,i);
        status="unique_hash";
      }
    }
    return Object.freeze({
      ...r,
      duplicateReview:Object.freeze({status,duplicateOfIndex})
    });
  });
  return Object.freeze({
    schemaVersion:CASE_LAW_METADATA_SCHEMA,
    processorVersion:CASE_LAW_METADATA_VERSION,
    recordCount:records.length,
    duplicateHashCount,
    records:Object.freeze(records),
    humanGateRequired:true,
    officialIdentifierGeneration:false
  });
}

