function norm(value){
  return String(value||"").normalize("NFKC").toLocaleLowerCase("mk").replace(/\s+/g," ").trim();
}

function numberOf(article){
  return norm(article?.articleNumberNormalized||article?.articleNumber||article?.article_number_normalized||article?.article_number||"")
    .replace(/^член\s*/u,"")
    .replace(/\s+/g,"");
}

function textOf(article){
  return [
    article?.heading||article?.article_heading||"",
    article?.text||article?.article_text||""
  ].filter(Boolean).join(" ").normalize("NFKC").replace(/\s+/g," ").trim();
}

export function isZkpDetentionAppealRequest(query){
  const q=norm(query);
  if(!q) return false;
  const detention=/(?:притвор|куќен притвор|лишување од слобода)/u.test(q);
  const remedy=/(?:жалб|правен лек|оспор|укинувањ|преинач)/u.test(q);
  return detention&&remedy;
}

