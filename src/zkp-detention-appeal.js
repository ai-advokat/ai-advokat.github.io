export const ZKP_DETENTION_APPEAL_VERSION="AI_ADVOCAT_ZKP_DETENTION_APPEAL_V1";
export const ZKP_DETENTION_APPEAL_ARTICLES=Object.freeze(["164","165","166","167","168","169"]);

function norm(value){
  return String(value||"").normalize("NFKC").toLocaleLowerCase("mk").replace(/\s+/g," ").trim();
}

function numberOf(article){
  return norm(article?.articleNumberNormalized||article?.articleNumber||article?.article_number_normalized||article?.article_number||"")
    .replace(/^член\s*/u,"")
    .replace(/\s+/g,"");
}

function headingOf(article){
  return String(article?.heading||article?.article_heading||"").normalize("NFKC").trim();
}

function textOf(article){
  return String(article?.text||article?.article_text||"").normalize("NFKC").replace(/\s+/g," ").trim();
}

function evidenceOf(article){
  return [headingOf(article),textOf(article)].filter(Boolean).join(" ");
}

export function isZkpDetentionAppealRequest(query){
  const q=norm(query);
  if(!q) return false;
  const asksAppeal=/(?:жалб|zalb|appeal)/u.test(q);
  const detention=/(?:притвор|detention)/u.test(q);
  if(!asksAppeal||!detention) return false;

  // V1 is deliberately bounded to the initial order determining detention.
  // Extension/revocation and post-indictment/post-judgment phases have their
  // own procedural rules and must not be silently folded into this lane.
  const otherPhase=/(?:продолжувањ|продолжен|укинувањ|укинување|по\s+поднесување\s+обвин|по\s+обвинителен\s+акт|по\s+објавување\s+на\s+пресуд|член\s*17[234])/u.test(q);
  if(otherPhase) return false;

  return /(?:решени|определувањ|определен|притвор)/u.test(q);
}

function sourceSignals(byNumber){
  const a164=evidenceOf(byNumber.get("164"));
  const a165=evidenceOf(byNumber.get("165"));
  const a167=evidenceOf(byNumber.get("167"));
  const a169=evidenceOf(byNumber.get("169"));
  return {
    proportionality:/(?:најкратко\s+нужно\s+време|сразмерност|притворот\s+ќе\s+се\s+укине)/iu.test(a164),
    grounds:/(?:основано\s+сомневање|ќе\s+се\s+определи\s+притвор|притвор\s+може\s+да\s+се\s+определи)/iu.test(a165),
    reasoning:/(?:факти\s+и\s+докази|основаното\s+сомневање|друга\s+мерка\s+за\s+обезбедување\s+присуство|друга\s+мерка.*присуство)/iu.test(a167),
    appeal24:/24\s*час/iu.test(a169),
    council48:/48\s*час/iu.test(a169),
    nonSuspensive:/(?:жалбата\s+не\s+го\s+задржува\s+извршувањето|не\s+го\s+задржува\s+извршувањето)/iu.test(a169)
  };
}

