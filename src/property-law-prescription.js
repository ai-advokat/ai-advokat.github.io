function norm(value){
  return String(value||"")
    .normalize("NFKC")
    .toLocaleLowerCase("mk")
    .replace(/[ќ]/g,"к")
    .replace(/[čć]/g,"c")
    .replace(/[ž]/g,"z")
    .replace(/[š]/g,"s")
    .replace(/\s+/g," ")
    .trim();
}

export function isPropertyPrescriptionQuery(query){
  const q=norm(query);
  if(!q) return false;
  const exact=/(?:одржувачк|odrzuvack|odrzhuvachk|usucapio|usucapi|acquisitive prescription)/u.test(q);
  if(exact) return true;

  const longPossession=/(?:долготрајн|долгогодишн|повеке\s+години|20\s+години|10\s+години).*?(?:владени|посед)/u.test(q)
    || /(?:владени|посед).*?(?:долготрајн|долгогодишн|повеке\s+години|20\s+години|10\s+години)/u.test(q);
  const propertyContext=/(?:сопственост|недвижн|имот|парцела|земјишт|кука|стан|стварн(?:о|и)\s+прав)/u.test(q);
  return longPossession&&propertyContext;
}

function asksDraft(query){
  return /(?:тужб|состави|подготви|изработи|напиши|поднесок|тужбено\s+барање)/u.test(norm(query));
}

function asksCaseLaw(query){
  return /(?:судск(?:а|и)\s+(?:практик|пракс)|пресуд|одлук|case\s*law)/u.test(norm(query));
}

